import * as Blockly from 'blockly';

// C++ operator precedence, lower binds tighter; valueToCode uses it to decide on parentheses.
export const Order = {
    ATOMIC: 0,
    FUNCTION_CALL: 2,
    UNARY: 3,
    MULTIPLICATIVE: 5,
    ADDITIVE: 6,
    RELATIONAL: 9,
    EQUALITY: 10,
    LOGICAL_AND: 14,
    LOGICAL_OR: 15,
    NONE: 99,
};

export class ArduinoGenerator extends Blockly.CodeGenerator {
    private readonly includes = new Map<string, string>();
    private readonly setup = new Map<string, string>();
    // Bodies of the start/loop hat blocks, in workspace order.
    readonly start: string[] = [];
    readonly loop: string[] = [];

    constructor() {
        super('arduino');
        this.INDENT = '  ';
    }

    override init(_workspace: Blockly.Workspace): void {
        this.includes.clear();
        this.setup.clear();
        this.start.length = 0;
        this.loop.length = 0;
        this.isInitialized = true;
    }

    // Built from the hat sections only: stacks outside a hat never run on the board, so `code` is dropped.
    override finish(_code: string): string {
        const setupLines = [...this.setup.values()].map((line) => `${line}\n`);
        const sections = [
            '// Generated by ThingBlock',
            [...this.includes.values()].join('\n'),
            this.func('setup', [...setupLines, ...this.start].join('')),
            this.func('loop', this.loop.join('')),
        ];
        this.isInitialized = false;

        return sections.filter(Boolean).join('\n\n') + '\n';
    }

    // Chains the next statement; hats have no previous connection and route their own chain into a section.
    override scrub_(block: Blockly.Block, code: string, thisOnly?: boolean): string {
        if (thisOnly || !block.previousConnection) return code;
        return code + this.blockToCode(block.getNextBlock());
    }

    // C string literal; Blockly has no default and single quotes would be a char in C++.
    quote_(text: string): string {
        const escaped = text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
        return `"${escaped}"`;
    }

    private func(name: string, body: string): string {
        return `void ${name}() {\n${body ? this.prefixLines(body, this.INDENT) : ''}}`;
    }
}

export const arduinoGenerator = new ArduinoGenerator();
