import * as Blockly from 'blockly';

class ArduinoGenerator extends Blockly.CodeGenerator {
    private readonly includes = new Map<string, string>();
    private readonly setup = new Map<string, string>();

    constructor() {
        super('arduino')
        this.INDENT = '  ';
    }

    override init(_workspace: Blockly.Workspace): void {
        this.includes.clear();
        this.setup.clear();
    }

    override finish(code: string): string {
        const setupCode = this.prefixLines([this.setup.values()].join('\n'), this.INDENT);
        const loopCode = this.prefixLines(code.trimEnd(), this.INDENT);
        const sections = [
            '// Generated by ThingBlock',
            [this.includes.values()].join('\n'),
            `void setup() {\n${setupCode}\n}`,
            `void loop() {\n${loopCode}\n}`,
        ];

        return sections.filter(Boolean).join('\n\n') + '\n';
    }
}

export const arduinoGenerator = new ArduinoGenerator;