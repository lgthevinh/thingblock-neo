import * as Blockly from 'blockly';
import type { OpName } from './thingbot_vm/opcode.ts';

// Stack code never needs parentheses: values are ATOMIC and inputs are read at NONE.
export const Order = {
    ATOMIC: 0,
    NONE: 99,
};

export const MAX_VARIABLES = 16;

/** One assembly line: an opcode with an optional operand (a number or a label). */
export function op(name: OpName, operand?: number | string): string {
    return operand === undefined ? `${name}\n` : `${name} ${operand}\n`;
}

/** Code that pushes the value of a block input, or 0 when it is empty. */
export function value(block: Blockly.Block, generator: ThingbotVmGenerator, input: string): string {
    return generator.valueToCode(block, input, Order.NONE) || op('PSH', 0);
}

/**
 * Compiles a workspace to a ThingBot VM program, emitted as the comma-separated slots of a C array.
 *
 * Handlers return assembly text, one instruction per line, with `name:` lines marking labels;
 * `finish` resolves labels to absolute slot indices.
 */
export class ThingbotVmGenerator extends Blockly.CodeGenerator {
    private readonly variables = new Map<string, number>();
    private labelCount = 0;
    // Bodies of the `when run` hat blocks, in workspace order.
    readonly start: string[] = [];
    /** Code that turns off each output the program used, run before HLT. */
    readonly stops = new Set<string>();

    constructor() {
        super('thingbot_vm');
        this.INDENT = '';
    }

    override init(_workspace: Blockly.Workspace): void {
        this.variables.clear();
        this.labelCount = 0;
        this.start.length = 0;
        this.stops.clear();
        this.isInitialized = true;
    }

    // Only `when run` stacks run on the robot; loose blocks are left out of the program.
    override workspaceToCode(workspace: Blockly.Workspace): string {
        this.init(workspace);
        for (const block of workspace.getTopBlocks(true)) {
            if (block.type === 'event_when_run') this.blockToCode(block);
        }
        return this.finish('');
    }

    // Blocks the VM can't run generate nothing: a statement passes on to the next one, a value reads as empty.
    override blockToCode(block: Blockly.Block | null, thisOnly?: boolean): string | [string, number] {
        if (block && !this.forBlock[block.type]) return this.scrub_(block, '', thisOnly);
        return super.blockToCode(block, thisOnly);
    }

    override finish(_code: string): string {
        // The VM keeps variable slots between runs, so start them from 0.
        let asm = [...this.variables.values()].map((slot) => op('PSH', 0) + op('STORE', slot)).join('');
        // Outputs hold their last value after HLT.
        asm += this.start.join('') + [...this.stops].join('') + op('HLT');
        this.isInitialized = false;
        return assemble(asm);
    }

    // Chains the next statement; hats have no previous connection and route their own chain into a section.
    override scrub_(block: Blockly.Block, code: string, thisOnly?: boolean): string {
        if (thisOnly || !block.previousConnection) return code;
        return code + this.blockToCode(block.getNextBlock());
    }

    /** A new unique label name. */
    label(): string {
        return `L${this.labelCount++}`;
    }

    /** The slot of a Blockly variable, allocated on first use. */
    variable(id: string): number {
        let slot = this.variables.get(id);
        if (slot === undefined) {
            if (this.variables.size === MAX_VARIABLES) {
                throw new Error(`ThingBot supports at most ${MAX_VARIABLES} variables`);
            }
            slot = this.variables.size;
            this.variables.set(id, slot);
        }
        return slot;
    }
}

// Two passes: place labels at slot indices, then emit one row per instruction.
function assemble(asm: string): string {
    const lines = asm.split('\n').filter(Boolean);
    const labels = new Map<string, number>();
    let slot = 0;
    for (const line of lines) {
        if (line.endsWith(':')) labels.set(line.slice(0, -1), slot);
        else slot += line.includes(' ') ? 2 : 1;
    }

    const rows: string[] = [];
    slot = 0;
    for (const line of lines) {
        if (line.endsWith(':')) continue;
        const [name, operand] = line.split(' ');
        const value = operand === undefined ? '' : ` ${labels.get(operand) ?? operand},`;
        rows.push(`${`${name},${value}`.padEnd(14)}// ${slot}`);
        slot += operand === undefined ? 1 : 2;
    }

    return `// Generated by ThingBlock\n${rows.join('\n')}\n`;
}

export const thingbotVmGenerator = new ThingbotVmGenerator();
